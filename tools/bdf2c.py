# converts X11 misc-fixed BDF fonts (public domain) into src/render/fonts.c + fonts.h.
#
#   python3 tools/bdf2c.py <dir with the .bdf files> src/render 5x7 6x10 8x13 ...
#
# each font keeps ASCII 32-126 plus Fluxion's special characters (codes from layout.h),
# taken from the fonts' own Unicode glyphs. widths are trimmed to the ink + a 1 px gap,
# so the fonts come out proportinal ('1' and 'i' are narrow), which looks way more
# like real typeset math and less like a terminal. (the spacing took forever ugh)

import os, sys

SPECIAL = {          # Fluxion code -> Unicode
    1: 0x03C0,       # CH_PI     pi
    2: 0x03B8,       # CH_THETA  theta
    3: 0x2212,       # CH_MINUS  minus sign
    4: 0x00B7,       # CH_CDOT   middle dot
}

# constants that share a letter with a variable: drawn bold, so the constant e and a
# variable e never look the same (the nspire uses a special e/i for the same reason).
BOLD = {             # Fluxion code -> the letter to thicken
    5: ord('e'),     # CH_EULER  e = 2.718...
    6: ord('i'),     # CH_IMAG   i = sqrt(-1)
}
LABELS = {1: 'pi', 2: 'theta', 3: 'minus', 4: 'cdot', 5: 'euler e', 6: 'imaginary i'}

def parse_bdf(path):
    props, glyphs = {}, {}
    with open(path, encoding='latin-1') as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        parts = line.split()
        if not parts:
            continue
        if parts[0] in ('FONT_ASCENT', 'FONT_DESCENT'):
            props[parts[0]] = int(parts[1])
        elif parts[0] == 'STARTCHAR':
            enc = dwidth = bbx = None
            rows = []
            for line in lines:
                p = line.split()
                if p[0] == 'ENCODING':
                    enc = int(p[1])
                elif p[0] == 'DWIDTH':
                    dwidth = int(p[1])
                elif p[0] == 'BBX':
                    bbx = tuple(int(v) for v in p[1:5])
                elif p[0] == 'BITMAP':
                    for line in lines:
                        if line.strip() == 'ENDCHAR':
                            break
                        rows.append(int(line.strip(), 16))
                    break
            glyphs[enc] = (dwidth, bbx, rows)
    return props['FONT_ASCENT'], props['FONT_DESCENT'], glyphs

def cell(ascent, height, glyph):
    """glyph -> list of `height` ints, bit 15 = leftmost column of the cell."""
    dwidth, (w, h, xo, yo), rows = glyph
    out = [0] * height
    nbytes = (w + 7) // 8
    for j, bits in enumerate(rows):
        r = ascent - (yo + h) + j
        if not 0 <= r < height:
            continue
        for c in range(w):
            if bits & (1 << (nbytes * 8 - 1 - c)):
                x = xo + c
                if 0 <= x < 16:
                    out[r] |= 0x8000 >> x
    return out

def convert(path):
    ascent, descent, glyphs = parse_bdf(path)
    height = ascent + descent
    space_dw = glyphs[32][0]
    rows_all, advances = [], []
    for code in range(128):
        src = SPECIAL.get(code, BOLD.get(code, code if 32 <= code <= 126 else None))
        if src is None or src not in glyphs:
            rows_all.append([0] * height)
            advances.append(0)
            continue
        rows = cell(ascent, height, glyphs[src])
        if code in BOLD:
            rows = [(r | (r >> 1)) & 0xFFFF for r in rows]
        ink = 0
        for r in rows:
            ink |= r
        if ink == 0:                        # space
            advances.append(max(space_dw - 1, 2))
        else:
            first = next(c for c in range(16) if ink & (0x8000 >> c))
            last = max(c for c in range(16) if ink & (0x8000 >> c))
            rows = [(r << first) & 0xFFFF for r in rows]
            advances.append(last - first + 2)
        rows_all.append(rows)
    return ascent, descent, rows_all, advances

def main():
    src_dir, out_dir, names = sys.argv[1], sys.argv[2], sys.argv[3:]
    c = ['/* GENERATED by tools/bdf2c.py from the X11 misc-fixed fonts',
         '   ("Public domain font. Share and enjoy."). edit the generator, not this file. */',
         '', '#include "fonts.h"', '']
    h = ['/* GENERATED by tools/bdf2c.py. edit the generator, not this file. */', '',
         '#ifndef FLUXION_FONTS_H', '#define FLUXION_FONTS_H', '',
         '/* a bitmap font: rows[code * height + row], bit 15 = leftmost pixel.',
         '   codes 32-126 are ASCII, 1-4 are the special characters in layout.h. */',
         'typedef struct {',
         '    const char *name;',
         '    unsigned char ascent, descent;      /* rows above / below the baseline */',
         '    const unsigned char *advance;       /* [128] pixels to the next character */',
         '    const unsigned short *rows;         /* [128 * (ascent + descent)] */',
         '} font_t;', '']
    for name in names:
        ascent, descent, rows_all, advances = convert(os.path.join(src_dir, name + '.bdf'))
        ident = 'font_' + name.replace('x', '_')
        c.append(f'static const unsigned char {ident}_advance[128] = {{')
        for i in range(0, 128, 16):
            c.append('    ' + ', '.join(str(a) for a in advances[i:i + 16]) + ',')
        c.append('};')
        c.append(f'static const unsigned short {ident}_rows[128 * {ascent + descent}] = {{')
        for code, rows in enumerate(rows_all):
            label = repr(chr(code)) if 32 <= code <= 126 else LABELS.get(code, str(code))
            if not any(rows) and code not in (32,):
                c.append('    ' + ', '.join('0' for _ in rows) + ',')
                continue
            c.append('    ' + ', '.join(f'0x{r:04X}' for r in rows) + f',  /* {label} */')
        c.append('};')
        c.append(f'const font_t {ident} = {{ "{name}", {ascent}, {descent}, {ident}_advance, {ident}_rows }};')
        c.append('')
        h.append(f'extern const font_t {ident};')
    h += ['', '#endif', '']
    with open(os.path.join(out_dir, 'fonts.c'), 'w') as f:
        f.write('\n'.join(c))
    with open(os.path.join(out_dir, 'fonts.h'), 'w') as f:
        f.write('\n'.join(h))

main()
