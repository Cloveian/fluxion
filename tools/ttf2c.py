# subsets the DejaVu Sans faces down to what Fluxion draws and writes them as C arrays, src/render/vfonts.c + vfonts.h. needs fonttools (pip install fonttools).
#
#   python3 tools/ttf2c.py /usr/share/fonts/TTF src/render
#
# vfonts-LICENSE.txt (DejaVu / Bitstream Vera) has to ship with the output.

import io, os, sys
from fontTools import subset
from fontTools.ttLib import TTFont

FACES = [                     # C name, file in the font directory
    ('regular',      'DejaVuSans.ttf'),
    ('bold',         'DejaVuSans-Bold.ttf'),
    ('oblique',      'DejaVuSans-Oblique.ttf'),
    ('bold_oblique', 'DejaVuSans-BoldOblique.ttf'),
]

# ASCII, Greek, and the math signs from layout.h and editor.h
UNICODES = (list(range(0x20, 0x7F)) + [0xB0, 0xB1, 0xB7, 0xD7, 0xF7] + list(range(0x391, 0x3CA))
            + [0x2192, 0x2211, 0x2212, 0x221A, 0x221E, 0x222B, 0x2248, 0x2260, 0x2264, 0x2265, 0x22C5])

def subset_face(path):
    opts = subset.Options()
    opts.layout_features = []
    opts.hinting = False
    opts.desubroutinize = True
    opts.name_IDs = []                  # no name table, the licence wants modified copies renamed
    opts.drop_tables += ['name', 'GPOS', 'GSUB', 'GDEF', 'kern', 'FFTM']
    font = TTFont(path, recalcTimestamp=False)      # else head.modified is now() and the output changes every run
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()

def main():
    src, dest = sys.argv[1], sys.argv[2]
    h = ['/* GENERATED by tools/ttf2c.py. edit the generator, not this file. */', '',
         '#ifndef FLUXION_VFONTS_H', '#define FLUXION_VFONTS_H', '',
         '/* DejaVu Sans, subset. see vfonts-LICENSE.txt */', '']
    c = ['/* GENERATED by tools/ttf2c.py. edit the generator, not this file. */', '',
         '#include "platform/screen.h"', '#include "vfonts.h"', '', '#ifdef SCREEN_RESIZABLE', '']
    for name, file in FACES:
        data = subset_face(os.path.join(src, file))
        h.append(f'extern const unsigned char vface_{name}[];')
        h.append(f'extern const unsigned int vface_{name}_len;')
        c.append(f'/* {file}, {len(data)} bytes */')
        c.append(f'const unsigned int vface_{name}_len = {len(data)};')
        c.append(f'const unsigned char vface_{name}[] = {{')
        for i in range(0, len(data), 24):
            c.append('    ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
        c.append('};')
        c.append('')
    h += ['', '#endif', '']
    c += ['#else', 'typedef int vfonts_unused; /* the calculators and the web page keep the bitmap fonts */', '#endif', '']
    with open(os.path.join(dest, 'vfonts.h'), 'w') as f:
        f.write('\n'.join(h))
    with open(os.path.join(dest, 'vfonts.c'), 'w') as f:
        f.write('\n'.join(c))

main()
